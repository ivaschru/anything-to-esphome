// The two exact public select values are also the local menu labels. Invalid
// input preserves the last valid choice rather than silently changing locale.
inline bool parse(const std::string &value,bool &english) {
  if(value=="English"){english=true;return true;}
  if(value=="Русский"){english=false;return true;}
  return false;
}
inline const char *text(bool english,const char *ru) {
  if(!english || !ru)return ru;
  for(const auto &label:LABELS)if(std::strcmp(ru,label.ru)==0)return label.en;
  return ru; // Latin units, product names and explicitly unknown text stay exact.
}
