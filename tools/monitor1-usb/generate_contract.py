#!/usr/bin/env python3
"""Generate the browser's fixed read-only USB contract from canonical inputs.

No device or private capture is opened. --check compares bytes without writing.
The browser probe is not the complete Python capture/apply controller: it
exports only filtered identity and verified source status, never a backup or
new install authority.
"""
import argparse
import importlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
PORT = ROOT / "ports/monitor1"
sys.path.insert(0, str(PORT))
try:
    preflight = importlib.import_module("preflight_adb")
finally:
    sys.path.pop(0)


def specification():
    identity = [
        {"name": "uid", "command": "id -u"},
        {"name": "wlan_mac", "command": "cat /sys/class/net/wlan0/address"},
        {"name": "version", "command": "cat /data/etc/os-release"},
        {"name": "arch", "command": "uname -m"},
        {"name": "co2_type", "command": preflight.CO2_READ},
        {"name": "boot_id", "command": "cat /proc/sys/kernel/random/boot_id"},
    ]
    files = []
    for path, (digest, size) in preflight.FILES.items():
        files.append({
            "command": "test ! -L " + path + "\ntest -f " + path +
                       "\nstat -c '%s %h' " + path + "\nsha256sum " + path,
            "expected": f"{size} 1\n{digest} {path}",
        })
    return {"identity": identity, "files": files,
            "absent_install": "test ! -e /data/.esphome-cgs1\ntest ! -L /data/.esphome-cgs1"}


def content():
    value = specification()
    return ("// Generated by tools/monitor1-usb/generate_contract.py; never edit pins here.\n"
            "// Fixed read-only commands from ports/monitor1/preflight_adb.py; no INI body export.\n"
            "export const contract = " + json.dumps(value, ensure_ascii=True, indent=2) + ";\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {
        "custom_components/qingping_esphome/frontend/usb-probe-contract.mjs": content(),
        "apps/monitor1_usb/rootfs/contract.json": json.dumps(specification(), indent=2) + "\n",
    }
    for name, data in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_text() != data:
                raise SystemExit("USB read contract is stale: " + name)
        else:
            path.write_text(data)


if __name__ == "__main__":
    main()
