#!/usr/bin/env python3
"""Deterministic HACS copy of the shared USB engine and its offline UI.

Keep one authored engine for the legacy app and Core. Only this explicit public
file set is copied; no job/profile/SDK/log/native program can enter the HACS ZIP.
CI --check refuses stale or extra files rather than shipping divergent helpers.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "apps/monitor1_usb/rootfs"
COMPONENT = ROOT / "custom_components/qingping_esphome"
FILES = (
    "browser_payload.py", "browser_plan.py", "browser_plan_job.py", "browser_stage.py", "browser_disabled_commit_policy.py",
    "ha_enrollment.py", "ha_enrollment_usb.py",
    "backup_export.py", "build_worker.py", "computer_install.py", "computer_package.py",
    "full_ui_review.py", "full_ui_usb.py", "full_ui_trial.py", "full_ui_trial_usb.py", "full_ui_installation.py", "install_plan.py", "installation.py",
    "pm_extension_guard.py", "pm_extension_usb.py", "pm_extension_installation.py",
    "full_ui_activation.py", "full_ui_activation_usb.py", "full_ui_activation_installation.py",
    "preparation.py", "server.py", "usb_install_job.py", "core_actor.py", "core_tools.py",
    "contract.json", "core-tools.json", "computer-instructions.txt",
)
ASSETS = ("app.mjs", "index.html", "style.css", "usb-probe-bundle.mjs", "usb-probe-NOTICES.txt", "core-bridge.mjs")


def package(root=ROOT, check=False):
    source = root / "apps/monitor1_usb/rootfs"
    component = root / "custom_components/qingping_esphome"
    expected = {component / "monitor1_worker" / name: (source / name).read_bytes() for name in FILES}
    expected[component / "monitor1_worker/__init__.py"] = b'"""Generated by tools/monitor1-usb/package_core.py; edit shared app sources."""\n'
    expected.update({component / "frontend/monitor1" / name: (source / "static" / name).read_bytes() for name in ASSETS})
    actual = {p for directory in (component / "monitor1_worker", component / "frontend/monitor1")
              if directory.exists() for p in directory.rglob("*") if p.is_file() and "__pycache__" not in p.parts}
    if actual - set(expected):
        raise SystemExit("Unexpected file in generated Core package")
    for target, data in expected.items():
        if check:
            if not target.is_file() or target.read_bytes() != data:
                raise SystemExit("Stale generated Core package: " + str(target.relative_to(root)))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    package(check=parser.parse_args().check)
