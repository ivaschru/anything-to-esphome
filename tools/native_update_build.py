"""Public, bounded patch table for ESP32's own credential-preserving updater.

Offsets refer to the original immutable application, never a private image.
The ESP32 verifies the original SHA before activating the personalized slot.
Markers in the updater itself are XOR encoded: otherwise the ordinary initial
personalizer would replace its reference markers along with the boot slots.
"""
import importlib.util
from pathlib import Path

def image_module(root):
    spec = importlib.util.spec_from_file_location("qf_native_image", Path(root) / "custom_components/qingping_esphome/image.py")
    module = importlib.util.module_from_spec(spec); spec.loader.exec_module(module)
    return module

def marker_header(root):
    slots = image_module(root).SLOTS
    lines = ["// Generated by tools/native_update_build.py; no private values.", "#pragma once",
             "#include <cstddef>", "#include <cstdint>", "namespace esphome::qf_native_update {",
             f"inline constexpr size_t SLOT_COUNT = {len(slots)};"]
    for i, marker in enumerate(slots.values()):
        lines.append(f"inline const volatile uint8_t encoded_{i}[] = {{" + ",".join(str(b ^ 165) for b in marker) + "};")
    lines += ["inline uint8_t marker_byte(size_t slot, size_t at) {", "  switch (slot) {"]
    for i in range(len(slots)): lines.append(f"    case {i}: return encoded_{i}[at] ^ 165;")
    lines += ["    default: return 0;", "  }", "}", "inline size_t marker_size(size_t slot) {", "  switch (slot) {"]
    for i, marker in enumerate(slots.values()): lines.append(f"    case {i}: return {len(marker)};")
    lines += ["    default: return 0;", "  }", "}", "}  // namespace esphome::qf_native_update", ""]
    return "\n".join(lines)

def patch_table(root, binary):
    image = image_module(root)
    ranges, _, _ = image.layout(binary)
    patches = []
    for i, marker in enumerate(image.SLOTS.values()):
        start = 0; count = 0
        while (at := binary.find(marker, start)) >= 0:
            if not any(a <= at and at + len(marker) <= b for a, b in ranges):
                raise ValueError("Native patch outside application data")
            patches.append([at, i]); count += 1; start = at + len(marker)
        if not count: raise ValueError("Missing native personalization slot")
    patches.sort()
    if len(patches) > 128: raise ValueError("Too many native patches")
    for (at, slot), (nxt, _) in zip(patches, patches[1:]):
        if at + len(list(image.SLOTS.values())[slot]) > nxt:
            raise ValueError("Overlapping native patches")
    return patches
