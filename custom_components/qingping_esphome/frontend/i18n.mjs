export const LANGUAGE_KEY = "qingping-esphome-language";
export const normalizeLanguage = value => value === "ru" ? "ru" : "en";
export const t = (language, key) => (Object.hasOwn(MESSAGES.en, key) ? MESSAGES[normalizeLanguage(language)][key] : MESSAGES.en.operation_failed);
export const failure = code => Object.assign(new Error(t("en", code)), {code});
export function readLanguage() {
  try { return normalizeLanguage(globalThis.localStorage?.getItem(LANGUAGE_KEY)); }
  catch { return "en"; }
}
export function saveLanguage(language) {
  try { globalThis.localStorage?.setItem(LANGUAGE_KEY, normalizeLanguage(language)); }
  catch { /* Storage can be blocked; the current panel still changes language. */ }
}
export function errorKey(error) {
  const code = String(error?.code || "").replace(/^qingping_/, "");
  if (Object.hasOwn(MESSAGES.en, code)) return code;
  if (error?.name === "NotFoundError") return "bluetooth_cancelled";
  if (error?.name === "NetworkError") return "ble_disconnected";
  if (error?.name === "SecurityError") return "bluetooth_unavailable";
  return "operation_failed";
}
